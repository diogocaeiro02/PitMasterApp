import assert from 'node:assert/strict'
import { createSimulation, advanceSimulation, triggerSimulationPit, triggerSimulationIncident, setSimulationScenario } from './src/simulator.ts'
const racers = Array.from({length:20},(_,i)=>({id:`r${i}`,position:i+1,kart:String(i+1),name:`Equipa ${i+1}`,bestLap:'1:04.500',lastLap:'',gap:'',interval:'',onTrack:'',pits:'',laps:0,sectors:['','','']}))
let sim = createSimulation(racers,'7',['A','B','C'],1700000000000)
assert.equal(sim.timeMs,720000)
assert.ok(sim.timing.lapHistory.length>=100, 'O pre-aquecimento deve produzir voltas')
assert.ok(sim.timing.passages.length>100)
assert.ok(sim.timing.racers.length===20)
sim=setSimulationScenario(sim,'slow-track')
sim=advanceSimulation(sim,60000)
assert.equal(sim.timeMs,780000)
sim=triggerSimulationIncident(sim,'warning','7')
assert.equal(sim.timing.raceControl.length,1)
sim=triggerSimulationPit(sim)
assert.equal(sim.pitVisits.length,1)
sim=advanceSimulation(sim,60000)
assert.equal(sim.pitVisits[0].exitedAt!==undefined,true)
assert.equal(sim.driverIndex,1)
assert.equal(sim.stints.length,2,'O simulador deve guardar o histórico dos stints')
assert.ok(sim.stints[0].endedAt && sim.stints[1].endedAt === undefined)
console.log('Simulador: 20 karts, passagens, 12 min de histórico, warning e pit validados.')
