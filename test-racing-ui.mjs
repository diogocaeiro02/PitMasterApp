import {readFileSync} from 'node:fs'
import assert from 'node:assert/strict'
const text=(path)=>readFileSync(`src/${path}`,'utf8')
const setup=text('RaceSetup.tsx')
const calendar=text('RaceCalendar.tsx')
const strategy=text('StrategyPanel.tsx')
const race=text('main.tsx')
const css=text('racing-v21.css')
assert(!setup.includes('sprintPresetCard'),'Cartão promocional 10+30 não pode voltar')
assert(!setup.includes('<aside className="card raceHubLibrary"'),'Biblioteca de provas não deve duplicar o assistente')
assert(setup.includes('raceSetupManage'),'Gestão de prova deve continuar acessível')
assert(calendar.includes("CalendarView='month'|'list'"),'Calendário tem duas vistas')
assert(calendar.includes('calendarAgendaItems')&&calendar.includes('calendarOverview'),'Calendário tem agenda e resumo')
assert(strategy.includes('{plan.length > 0 && <div className="strategyScoreGrid">'),'Os indicadores vazios devem ficar ocultos')
assert(strategy.includes('Criar primeiro stint'),'Ação inicial da estratégia')
assert(race.indexOf('className={`lapSpotlight') < race.indexOf('className="heroMetrics"'),'Lap Performance primeiro')
assert(css.includes("--r-head:'Barlow Condensed'")&&css.includes('font-variant-numeric:tabular-nums'),'Fontes e tempo estável')
assert(css.includes('prefers-reduced-motion'),'Respeitar acessibilidade')
console.log('V0.21: fluxo, agenda, tipografia, layout e Lap Performance verificados.')
